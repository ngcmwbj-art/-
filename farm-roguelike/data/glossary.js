'use strict';
/* =========================================================
   言葉の説明（カードを大きく表示したときに、説明文に出てくる言葉の意味を下に出す）
   - キー：カードの文に出てくる言葉 / 値：説明
   - 種類（作物・常時など）の説明は TYPES
   ========================================================= */
FR.Glossary = {
  WORDS: {
    '勢い': '敵の体力。0 にすると追い払える',
    '守り': '敵から受ける被害を先に受け止める。自分のターンの始めに 0 に戻る',
    '健康度': '農場の体力。0 になると離農（挑戦の終わり）',
    'エネルギー': 'カードを使うのに要る力。毎ターン 3 に戻る',
    '廃棄': '使うと、この戦闘の間はデッキから消える（戦闘が終われば戻る）',
    '引く': '山札からカードを手札に取る',
    '銭': 'お金。市場でカードを買える。経営評価の点にもなる',
    '地力': '作物と木が育つたびに、この数だけ多く育つ',
    '段': '作物や家畜の育ち具合。決まった段まで育つと収穫・出荷できる',
    '成木': '育ちきった柑橘の木。毎ターン終わりに実が1つなる',
    '手入れ': '家畜にかけた手間。多いほど格付けが上がり高く売れる',
    '格付け': '出荷したときの等級。手入れで上がり、銭に倍率がかかる',
    '出荷': '育った家畜を売る。畜舎をタップするか、まとめて出荷',
    '収穫': '実った作物や実を取る。区画をタップするか、まとめて収穫',
    '奪われない': '鴉などに作物や実を取られない。霜や害虫の「しおれ」も防ぐ',
    '病気にかからない': '鳥インフルや家畜疫病の感染から家畜を守る',
    '敵すべて': '並んでいる敵の全員に効く',
    '次のターン始め': '敵が動いたあと、次の自分のターンになったとき'
  },
  TYPES: {
    power: '常時：使うと、この戦闘の間ずっと効き続ける',
    machine: '機械：強いが、エネルギーを多く使うものが多い',
    crop: '作物：畑の空いた区画に植える。育つと収穫できる',
    livestock: '畜産：畜舎の家畜に効く'
  },

  // カードの文に出てくる言葉の説明を [言葉, 説明] で返す
  forCard(v) {
    const out = [];
    const text = (v.text || '') + (v.name || '');
    for (const [w, t] of Object.entries(FR.Glossary.WORDS)) {
      if (text.includes(w)) out.push([w, t]);
    }
    if (FR.Glossary.TYPES[v.type]) {
      const [k, t] = FR.Glossary.TYPES[v.type].split('：');
      out.unshift([k, t]);
    }
    return out.slice(0, 5);
  },

  html(v) {
    const list = FR.Glossary.forCard(v);
    if (!list.length) return '';
    const E = FR.Util.escape;
    return '<dl class="terms-list">' + list.map(([w, t]) => `<dt>${E(w)}</dt><dd>${E(t)}</dd>`).join('') + '</dl>';
  }
};
