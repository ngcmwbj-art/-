export const F5_ADV = 6;
const cache = new Map<string, HTMLCanvasElement>();

/** Glyph for a character in a colour (arrows are ↑ ↓ ← →). */
function glyph(ch: string, color: string): HTMLCanvasElement | null {
  const key = `${ch}|${color}`;
  let c = cache.get(key);
  if (c) return c;
  const rows = G[ch] ?? G[ch.toUpperCase()];
  if (!rows) return null;
  const p = new PixelCanvas(5, 7);
  p.art(rows, { '#': color });
  c = p.toCanvas();
  cache.set(key, c);
  return c;
}

/** Width in pixels of a string in the 5×7 font. */
export function f5Width(s: string): number {
  return s.length ? s.length * F5_ADV - 1 : 0;
}

/**
 * Draw with the 5×7 font. Lowercase letters are drawn as capitals. `shadow`
 * adds a 1px paper shadow.
 */
export function f5(ctx: CanvasRenderingContext2D, s: string, x: number, y: number, color: string, o: { align?: 'left' | 'right' | 'center'; shadow?: string } = {}): number {
  const w = f5Width(s);
  let cx = Math.round(o.align === 'right' ? x - w : o.align === 'center' ? x - w / 2 : x);
  const cy = Math.round(y);
  for (const ch of s) {
    const code = ch.toUpperCase();
    if (code !== ' ') {
      if (o.shadow) {
        const sg = glyph(code, o.shadow);
        if (sg) ctx.drawImage(sg, cx + 1, cy + 1);
      }
      const g = glyph(code, color);
      if (g) ctx.drawImage(g, cx, cy);
    }
    cx += F5_ADV;
  }
  return w;
}
