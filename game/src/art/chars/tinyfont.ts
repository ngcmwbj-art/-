export function tinyWidth(s: string): number {
  return s.length * 4 - 1;
}

export function tinyText(g: Gfx, s: string, x: number, y: number, color: string, shadow?: string): void {
  const str = s.toLowerCase();
  const draw = (ox: number, oy: number, c: string) => {
    let cx = ox;
    for (const ch of str) {
      const m = G[ch] ?? G['?'];
      for (let j = 0; j < 5; j++) for (let i = 0; i < 3; i++) if (m[j * 3 + i] === '1') g.px(cx + i, oy + j, c);
      cx += 4;
    }
  };
  if (shadow) draw(x + 1, y + 1, shadow);
  draw(x, y, color);
}
