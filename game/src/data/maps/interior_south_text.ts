/** 文字幅の点検（southText）用：この部屋たちの全ページ。 */
export function southTexts(): [string, string][] {
  const out: [string, string][] = [];
  const walk = (name: string, v: unknown) => {
    if (typeof v === 'string') out.push([name, v]);
    else if (v && typeof v === 'object') for (const [k, x] of Object.entries(v)) walk(`${name}.${k}`, x);
  };
  walk('obj', SOBJ);
  walk('reward', SREWARD);
  walk('after', SREWARD_AFTER);
  walk('banner', { SBANNER, SBANNER_FLIP });
  walk('enter', SENTER);
  walk('talk', STALK);
  return out;
}
